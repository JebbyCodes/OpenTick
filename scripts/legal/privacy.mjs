#!/usr/bin/env node
// Generates src/js/privacy.gen.js: docs/privacy-policy.md as a string, so the app can show the policy offline (Settings -> About & privacy).
//   node scripts/legal/privacy.mjs           write the file
//   node scripts/legal/privacy.mjs --check   exit 1 if it is out of date (run by `npm test`)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const OUT = 'src/js/privacy.gen.js';
export const generate = () => `/* GENERATED by scripts/legal/privacy.mjs from docs/privacy-policy.md. Do not edit: edit the Markdown file and run \`npm run privacy\`. */\nconst PRIVACY_MD = ${JSON.stringify(readFileSync(join(root, 'docs/privacy-policy.md'), 'utf8'))};\n`;
if (process.argv[1] && process.argv[1].endsWith('privacy.mjs')) {
  const out = generate(), file = join(root, OUT);
  if (process.argv.includes('--check')) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== out) { console.error('privacy.gen.js is out of date: run `npm run privacy`'); process.exit(1); }
    console.log('privacy policy data is up to date');
  } else { writeFileSync(file, out); console.log('wrote ' + OUT); }
}
