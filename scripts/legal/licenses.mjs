#!/usr/bin/env node
// Generates src/js/licenses.gen.js: the third-party licence data shown in Settings -> About OpenTick -> Licences.
//   node scripts/legal/licenses.mjs           write the file
//   node scripts/legal/licenses.mjs --check   exit 1 if the file is out of date (run by `npm test`)
// Inputs (all in the repository, so the output is reproducible and has no timestamp):
//   package-lock.json          every npm package, its installed version and the licence the package declares
//   src-tauri/Cargo.toml       the direct Rust dependencies; Cargo.lock (when committed) gives the resolved versions, and when `cargo` is
//                              available `cargo metadata --offline` supplies every crate's declared licence (otherwise the direct ones fall back
//                              to the table below, marked "curated")
//   scripts/legal/licenses.assets.json  bundled assets and platform components that no package manager knows about (icons, logo, Android template)
//   scripts/legal/license-texts/*    the licence texts themselves; LICENSE is the project's own
// After changing dependencies or assets: `npm run licenses`, then commit the result.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..'), rd = p => readFileSync(join(root, p), 'utf8');
export const OUT = 'src/js/licenses.gen.js';
// official Tauri crates are dual licensed; this is only a fallback for when `cargo metadata` cannot run
const CURATED_RUST = (name) => (name === 'tauri' || name === 'serde_json' || name.startsWith('tauri-plugin-') ? 'Apache-2.0 OR MIT' : null);

export function npmComponents(lock) {
  return Object.entries(lock.packages || {}).filter(([k]) => k).map(([k, v]) => ({
    name: k.replace(/^.*node_modules\//, ''), version: v.version || '', license: v.license || 'UNKNOWN', ecosystem: 'npm',
    scope: v.dev ? 'Build tool (not part of the app you run)' : 'Bundled', url: `https://www.npmjs.com/package/${k.replace(/^.*node_modules\//, '')}`, source: 'package-lock.json',
  })).sort((a, b) => a.name.localeCompare(b.name));
}
export function cargoDirect(toml) {
  const sect = (toml.split(/^\[dependencies\]\s*$/m)[1] || '').split(/^\[/m)[0], out = [];
  for (const line of sect.split('\n')) { const m = /^([A-Za-z0-9_-]+)\s*=\s*(?:"([^"]+)"|\{[^}]*version\s*=\s*"([^"]+)")/.exec(line.trim()); if (m) out.push({ name: m[1], req: m[2] || m[3] }); }
  return out;
}
export function cargoLockVersions(lock) { const v = {}; for (const m of lock.matchAll(/\[\[package\]\]\s*\nname = "([^"]+)"\s*\nversion = "([^"]+)"/g)) (v[m[1]] = v[m[1]] || []).push(m[2]); return v; }
export function rustComponents(toml, lockText, metadata) {
  const lock = lockText ? cargoLockVersions(lockText) : null, byName = {};
  if (metadata) for (const p of metadata.packages || []) byName[p.name + '@' + p.version] = p;
  if (metadata) { // every crate in the resolved build, with the licence its own manifest declares
    return (metadata.packages || []).map(p => ({ name: p.name, version: p.version, license: p.license || 'UNKNOWN', ecosystem: 'crates.io', scope: 'Bundled (compiled into the app)', url: `https://crates.io/crates/${p.name}`, source: 'cargo metadata' }))
      .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
  }
  return cargoDirect(toml).map(d => ({ name: d.name, version: lock && lock[d.name] ? lock[d.name][0] : `${d.req} (not pinned: no Cargo.lock in the repository)`, license: CURATED_RUST(d.name) || 'UNKNOWN', ecosystem: 'crates.io',
    scope: 'Bundled (compiled into the app); its own dependencies are not listed here', url: `https://crates.io/crates/${d.name}`, source: 'curated (Cargo.toml direct dependencies)' })).sort((a, b) => a.name.localeCompare(b.name));
}
export function splitSpdx(expr) { return [...new Set(String(expr || '').split(/\s+(?:OR|AND|WITH)\s+|[()]/i).map(s => s.trim()).filter(Boolean))]; }

export function build({ lockJson, cargoToml, cargoLock, metadata, assets, texts, projectLicense, pkg }) {
  const comps = [...assets.components, ...npmComponents(lockJson), ...rustComponents(cargoToml, cargoLock, metadata)];
  const used = new Set(['Unlicense']); for (const c of comps) for (const id of splitSpdx(c.license)) used.add(id);
  const outTexts = {}; for (const id of [...used].sort()) if (texts[id]) outTexts[id] = texts[id];
  outTexts.Unlicense = projectLicense.trim();
  return { project: { name: pkg.name, license: 'Unlicense', repository: assets.repository, issues: assets.issues, releases: assets.releases }, notes: assets.notes, components: comps, texts: outTexts };
}
export function render(data) {
  const head = '/* GENERATED by scripts/legal/licenses.mjs from package-lock.json, src-tauri/Cargo.toml (+ Cargo.lock), scripts/legal/licenses.assets.json and scripts/legal/license-texts/. Do not edit: run `npm run licenses`. */\n';
  const comps = data.components.map(c => '    ' + JSON.stringify(c)).join(',\n');
  return `${head}const OT_LICENSES = {\n  project: ${JSON.stringify(data.project)},\n  notes: ${JSON.stringify(data.notes)},\n  components: [\n${comps}\n  ],\n  texts: ${JSON.stringify(data.texts)},\n};\n`;
}
function gather() {
  let metadata = null;
  if (existsSync(join(root, 'src-tauri/Cargo.lock'))) { try { metadata = JSON.parse(execFileSync('cargo', ['metadata', '--format-version', '1', '--locked', '--offline', '--manifest-path', join(root, 'src-tauri/Cargo.toml')], { encoding: 'utf8', maxBuffer: 1 << 28, stdio: ['ignore', 'pipe', 'ignore'] })); metadata.packages = metadata.packages.filter(p => !p.source === false || p.source); } catch (e) { /* no cargo here: fall back to the curated direct list */ } }
  const texts = {}; for (const id of ['MIT', 'ISC', 'Apache-2.0']) texts[id] = rd(`scripts/legal/license-texts/${id}.txt`).trim();
  return build({ lockJson: JSON.parse(rd('package-lock.json')), cargoToml: rd('src-tauri/Cargo.toml'), cargoLock: existsSync(join(root, 'src-tauri/Cargo.lock')) ? rd('src-tauri/Cargo.lock') : null, metadata,
    assets: JSON.parse(rd('scripts/legal/licenses.assets.json')), texts, projectLicense: rd('LICENSE'), pkg: JSON.parse(rd('package.json')) });
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = render(gather());
  if (process.argv.includes('--check')) { const cur = existsSync(join(root, OUT)) ? rd(OUT) : ''; if (cur !== out) { console.error(`${OUT} is out of date. Run: npm run licenses`); process.exit(1); } console.log('licence data is up to date'); }
  else { writeFileSync(join(root, OUT), out); console.log(`wrote ${OUT} (${out.length} bytes)`); }
}
